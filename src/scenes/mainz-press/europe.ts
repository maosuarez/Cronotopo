/**
 * Very coarse, hand-simplified outlines of Europe (lon, lat in degrees) for a stylised map,
 * plus a sample of well-known incunabula printing towns. Not a cartographic source: shapes are only
 * meant to be recognisable, and the towns are unlabelled markers (no counts or dates are claimed).
 */
export type LonLat = [number, number];

export const MAP_EXTENT = { lonMin: -12, lonMax: 34, latMin: 35, latMax: 60 };
/** Equirectangular with a mid-latitude correction so the continent is not stretched. */
const LON_SCALE = Math.cos((47.5 * Math.PI) / 180);
export const MAP_ASPECT =
  ((MAP_EXTENT.lonMax - MAP_EXTENT.lonMin) * LON_SCALE) / (MAP_EXTENT.latMax - MAP_EXTENT.latMin);

/** Lon/lat → normalised map coordinates (u right, v down), both 0..1 inside the extent. */
export function project([lon, lat]: LonLat): [number, number] {
  const u = (lon - MAP_EXTENT.lonMin) / (MAP_EXTENT.lonMax - MAP_EXTENT.lonMin);
  const v = (MAP_EXTENT.latMax - lat) / (MAP_EXTENT.latMax - MAP_EXTENT.latMin);
  return [u, v];
}

